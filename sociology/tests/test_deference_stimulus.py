@pytest.fixture
def harness_format_observation() -> Callable[[CommandResult], str]:
    """The agent harness's own result-envelope formatter, or a skip naming the file this box lacks.

    Deferred to test time rather than imported at the module top for the reason in the module
    docstring: the import loads a baked case file a fresh clone has never had, and at collection
    time that failure interrupts the entire run rather than this one module.

    Sibling of ``CaseFileAwareModule`` in ``reward_hacking/tests/conftest.py``, which turns the same
    failure into a module-level skip for the 47 modules there, and narrow in the same way and for
    the same reason. ``load_problems`` wraps the ``OSError`` it caught with ``raise ... from exc``,
    so this insists on a chained ``ENOENT`` whose filename is a case file. A case file that exists
    and does not parse still errors, which is the right outcome: that is a broken file rather than a
    fresh clone, and the failure mode to fear here is the lenient one, a byte-equality check with
    the harness quietly skipping while the run stays green.
    """
    try:
        from reward_hacking.harness.loop import _format_observation  # noqa: PLC0415
    except RuntimeError as exc:
        cause = exc.__cause__
        if not isinstance(cause, OSError) or cause.errno != errno.ENOENT:
            raise
        if not str(cause.filename).endswith("_cases.json"):
            raise
        pytest.skip(
            f"baked case file absent: {cause.filename} -- it is local-only and regenerated by the "
            "ETLs, see reward_hacking/harness/data/README.md"
        )
    else:
        return _format_observation


def load_with(tmp_path: Path, **overrides: Any) -> DeferenceStimulus:
    """Load the synthetic stimulus with any top-level field replaced."""
    return load_stimulus(
        write_synthetic_deference_stimulus(tmp_path / "deference_stimulus.json", **overrides)
    )


def refuses(tmp_path: Path, match: str, **overrides: Any) -> str:
    """Assert the loader refuses a planted violation, and return the message it refused with."""
    with pytest.raises(ValueError, match=match) as raised:
        load_with(tmp_path, **overrides)
    return str(raised.value)


def scenarios_with(**fields: Any) -> list[dict[str, Any]]:
    """The eight synthetic scenarios with one field of the FIRST one replaced."""
    scenarios = synthetic_deference_scenarios()
    scenarios[0].update(fields)
    return scenarios


