"""The deference stimulus loader and renderer: every refusal, every gate, and the render's shape.

Every class here is a refusal rather than a behaviour, and each covers a failure that would otherwise leave
a complete, plausible artifact behind: a brief both arms render identically, a report block that shows a
different number of agents than the paragraph states, a constraint that governs a dimension the fork does
not decide, a word of the safety or evaluation register in a prompt whose whole design rests on carrying
neither. The synthetic stimulus is the negative control for all of them -- it loads, so the eight renders of
a well-formed file pass every gate -- and each test plants exactly one violation into a copy of it.

One test here reads the agent harness's own result envelope, and reaching it is not free: importing
anything from ``reward_hacking.harness`` runs that package's ``__init__``, which reaches
``tasks_evalplus`` and loads ``harness/data/evalplus_cases.json`` at import time. That file is
local-only by privacy design (see the README beside it), so at the top of this module the import
aborted COLLECTION of the whole run -- ``Interrupted: 1 error during collection``, every other
suite included -- on any checkout that has never had it. It lives in
:func:`harness_format_observation` instead, so a fresh clone collects everything and skips that one
test by name.
"""

