class TestTheRenderedSections:
    def sections(
        self, stimulus: DeferenceStimulus, *, cell: str, arm: str = ARM_BREAKING
    ) -> tuple[str, ...]:
        return render_deference_sections(
            stimulus.scenarios[0],
            arm=arm,
            identity=identity_for_cell(cell),
            with_status_report=cell in {CELL_SAME_CHECKPOINT_CHOSE, CELL_DIFFERENT_FAMILY_CHOSE},
            print_order=LABEL_PRINT_ORDERS[0],
            stimulus=stimulus,
        )

    def test_the_peer_free_render_carries_no_paragraph_and_no_report(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        sections = self.sections(deference_stimulus, cell=CELL_NO_PEERS)
        joined = "\n\n".join(sections)
        assert DEFERENCE_PARAGRAPH_MARKER not in joined
        assert deference_stimulus.scenarios[0].status_command not in joined
        # brief, two log blocks, fork, instruction.
        assert len(sections) == brief_section_count(deference_stimulus.scenarios[0]) + 4

    def test_the_present_render_adds_the_paragraph_and_nothing_else(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        blind = self.sections(deference_stimulus, cell=CELL_NO_PEERS)
        present = self.sections(deference_stimulus, cell=CELL_SAME_CHECKPOINT_PRESENT)
        assert len(present) == len(blind) + 1
        inserted = [section for section in present if section not in blind]
        assert len(inserted) == 1
        assert inserted[0].startswith(DEFERENCE_PARAGRAPH_MARKER)

    def test_the_report_sits_after_the_own_log_and_is_the_only_addition(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        scenario = deference_stimulus.scenarios[0]
        present = self.sections(deference_stimulus, cell=CELL_SAME_CHECKPOINT_PRESENT)
        reported = self.sections(deference_stimulus, cell=CELL_SAME_CHECKPOINT_CHOSE)
        index = status_report_section_index(scenario, identity="same-checkpoint")
        assert reported[index] == status_report_block(scenario, deference_stimulus)
        assert (*reported[:index], *reported[index + 1 :]) == present

    def test_the_two_report_cells_report_blocks_are_byte_identical(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        """The report carries no identity, which is what makes the two cells differ in the paragraph."""
        scenario = deference_stimulus.scenarios[0]
        blocks = {
            cell: self.sections(deference_stimulus, cell=cell)[
                status_report_section_index(scenario, identity=identity_for_cell(cell))
            ]
            for cell in (CELL_SAME_CHECKPOINT_CHOSE, CELL_DIFFERENT_FAMILY_CHOSE)
        }
        assert len(set(blocks.values())) == 1

    def test_the_report_lists_one_line_per_other_agent_and_nothing_else(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        scenario = deference_stimulus.scenarios[0]
        lines = status_report_lines(scenario, deference_stimulus)
        assert len(lines) == PEER_COUNT
        assert [line.split("  ")[0] for line in lines] == list(peer_handles(PEER_COUNT))
        assert all(
            line.endswith(f"{scenario.status_field}: {scenario.deviation_label}") for line in lines
        )

    def test_the_print_orders_swap_the_fork_and_the_instruction_alone(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        rendered = {
            order: render_deference_sections(
                deference_stimulus.scenarios[0],
                arm=ARM_BREAKING,
                identity="same-checkpoint",
                with_status_report=True,
                print_order=order,
                stimulus=deference_stimulus,
            )
            for order in LABEL_PRINT_ORDERS
        }
        first, second = (rendered[order] for order in LABEL_PRINT_ORDERS)
        differing = [
            index
            for index, pair in enumerate(zip(first, second, strict=True))
            if pair[0] != pair[1]
        ]
        assert differing == [len(first) - 2, len(first) - 1]

    def test_the_arms_differ_in_the_constraint_sentence_alone(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        scenario = deference_stimulus.scenarios[0]
        rendered = {
            arm: self.sections(deference_stimulus, cell=CELL_NO_PEERS, arm=arm) for arm in ARMS
        }
        differing = [
            index
            for index, pair in enumerate(
                zip(rendered[ARM_BENIGN], rendered[ARM_BREAKING], strict=True)
            )
            if pair[0] != pair[1]
        ]
        assert len(differing) == 1
        assert scenario.constraint_benign in rendered[ARM_BENIGN][differing[0]]
        assert scenario.constraint_breaking in rendered[ARM_BREAKING][differing[0]]

    def test_the_labels_print_in_the_rows_own_order(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        scenario = deference_stimulus.scenarios[0]
        assert labels_in_print_order(scenario, LABEL_PRINT_ORDERS[0]) == (
            scenario.compliant_label,
            scenario.deviation_label,
        )
        assert labels_in_print_order(scenario, LABEL_PRINT_ORDERS[1]) == (
            scenario.deviation_label,
            scenario.compliant_label,
        )
        with pytest.raises(ValueError, match="print_order must be"):
            labels_in_print_order(scenario, "sideways")

    def test_the_instruction_is_the_games_own_and_asks_for_the_printed_pair(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        scenario = deference_stimulus.scenarios[0]
        sections = self.sections(deference_stimulus, cell=CELL_SAME_CHECKPOINT_CHOSE)
        assert sections[-1] == ONE_SHOT_INSTRUCTION.format(
            first_label=scenario.compliant_label, second_label=scenario.deviation_label
        )

    def test_every_cell_of_every_arm_renders_without_a_brace(
        self, deference_stimulus: DeferenceStimulus
    ) -> None:
        for scenario in deference_stimulus.scenarios:
            for arm in ARMS:
                for cell in CELLS:
                    for order in LABEL_PRINT_ORDERS:
                        prompt = render_deference_prompt(
                            scenario,
                            arm=arm,
                            cell=cell,
                            print_order=order,
                            stimulus=deference_stimulus,
                        )
                        assert "{" not in prompt
                        assert "}" not in prompt

